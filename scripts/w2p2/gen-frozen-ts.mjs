#!/usr/bin/env node
/**
 * Generates lib/role-shadow/frozen/*.ts (TypeScript literals) from the byte-verified JSON copies next to them.
 *
 * WHY: Turbopack's JSON importer is NOT bit-exact for floats (it can change a double by 1 ULP, e.g. 0.9240314943585303 -> 0.9240314943585304), so
 * importing the frozen JSON in a production BUILD silently alters frozen coefficients (the integrity guard then correctly refuses to run). The JS
 * compiler parses numeric LITERALS exactly, so the runtime module is generated as TS literals; test/role-shadow-frozen.test.ts proves every number is
 * bit-for-bit equal to the JSON and the JSON equals the W2.P1 original. Run: node scripts/w2p2/gen-frozen-ts.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const dir = join(dirname(fileURLToPath(import.meta.url)), "../../lib/role-shadow/frozen");
/** provenance prose stays in the reviewable JSON only: a code string naming a W2.P1 research path would (rightly) trip the W2.P1 production-boundary test */
const OMIT = ["_note", "source_file"];
const emit = (jsonFile, tsFile, exportName, comment) => {
  const parsed = JSON.parse(readFileSync(join(dir, jsonFile), "utf8"));
  for (const k of OMIT) delete parsed[k];
  const body = JSON.stringify(parsed, null, 1);
  writeFileSync(join(dir, tsFile), `// GENERATED by scripts/w2p2/gen-frozen-ts.mjs from ./${jsonFile} — do not edit. ${comment}\n// Numeric literals (not a JSON import): see the generator header for why.\nexport const ${exportName} = ${body} as const;\n`);
  console.log("wrote", tsFile);
};
emit("role-opportunity-challenger-2026.0.json", "challenger-spec.ts", "CHALLENGER_SPEC_LITERAL", "The W2.P1 SHADOW challenger spec.");
emit("w2p1-frozen-models-half.json", "models-half.ts", "FROZEN_MODELS_HALF_LITERAL", "The W2.P1 frozen HALF models (C0 and C2).");
